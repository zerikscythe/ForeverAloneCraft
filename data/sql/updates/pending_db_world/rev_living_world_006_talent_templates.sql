-- LivingWorld: bot talent tree templates + 19-build seed data (world DB)
-- talent_id = TalentEntry::TalentID from Talent.dbc (3.3.5a build 12340)
-- priority  = row*10+col for primary tree; +200 secondary; +300 tertiary

CREATE TABLE IF NOT EXISTS `living_world_bot_talent_template` (
    `template_id`  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `spec_key`     VARCHAR(32) NOT NULL,
    `class_id`     TINYINT UNSIGNED NOT NULL,
    `display_name` VARCHAR(64) NOT NULL,
    PRIMARY KEY (`template_id`),
    UNIQUE KEY `uk_lwbt_template_spec_class` (`spec_key`, `class_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `living_world_bot_talent_template_entry` (
    `entry_id`     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `template_id`  BIGINT UNSIGNED NOT NULL,
    `priority`     SMALLINT UNSIGNED NOT NULL,
    `talent_id`    SMALLINT UNSIGNED NOT NULL,
    `talent_name`  VARCHAR(64) NOT NULL DEFAULT '',
    `desired_rank` TINYINT UNSIGNED NOT NULL,
    PRIMARY KEY (`entry_id`),
    UNIQUE KEY `uk_lwbt_entry_talent` (`template_id`, `talent_id`),
    KEY `idx_lwbt_entry_priority` (`template_id`, `priority`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

